def set_language(lang: str) -> None:
    global _LANG
    _LANG = lang if lang in STRINGS else "en"


def current() -> str:
    return _LANG


def t(key: str, **kwargs) -> str:
    """Look up an interface string, falling back to English, then the key itself."""
    s = STRINGS.get(_LANG, {}).get(key) or STRINGS["en"].get(key, key)
    return s.format(**kwargs) if kwargs else s
